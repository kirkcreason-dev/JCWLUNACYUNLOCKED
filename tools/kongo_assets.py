def special_extract(im,anim):
    """Return reviewed ring/short-sheet crops, or None for connected silhouettes."""
    w,h=im.size
    if anim=='bat':
        # Contact bats touch the following panel's body. Follow each complete
        # silhouette so one attack never renders two extra miniature wrestlers.
        polygons=[[(10,335),(320,335),(320,815),(10,815)],[(343,225),(632,225),(632,819),(343,819)],
          [(704,447),(755,370),(884,368),(889,477),(928,530),(1066,549),(1070,579),(922,556),(882,585),(906,672),(927,756),(958,785),(956,810),(871,810),(852,753),(819,699),(731,700),(697,760),(698,808),(635,808),(634,784),(658,717),(672,685),(641,656),(655,620),(682,585),(701,545)],
          [(1052,462),(1090,365),(1215,363),(1234,459),(1253,523),(1270,564),(1378,592),(1374,627),(1261,594),(1241,651),(1253,712),(1269,761),(1288,783),(1287,812),(1209,812),(1192,761),(1169,700),(1080,702),(1058,751),(1036,788),(1038,809),(971,809),(970,783),(990,720),(1009,682),(991,660),(1029,583),(1050,548)],
          [(1363,354),(1590,354),(1590,817),(1320,817),(1320,732),(1346,681),(1376,620),(1379,593),(1363,560)]]
        result=[]
        for poly in polygons:
            mask=Image.new('1',im.size);ImageDraw.Draw(mask).polygon([(x*w/1600,y*h/900) for x,y in poly],fill=1)
            found=clean_mask(im,np.array(mask,dtype=bool))
            if found:result.append(max(found,key=lambda v:v['area']))
        return result
    if anim in ('climb','entry'):
        polygons=CLIMB if anim=='climb' else ENTRY
        base=(1600,533) if anim=='climb' else (1600,901)
        result=[]
        for poly in polygons:
            mask=Image.new('1',im.size)
            ImageDraw.Draw(mask).polygon([(x*w/base[0],y*h/base[1]) for x,y in poly],fill=1)
            found=clean_mask(im,np.array(mask,dtype=bool),rope=True,minheight=32)
            if found:result.append(max(found,key=lambda v:v['area']))
        return result
    if anim=='dive':
        boxes=[(.265,.34,.456,.66),(.453,.42,.747,.70)]
    elif anim=='fallFront':
        boxes=[(.012,.31,.166,.87),(.167,.38,.341,.87),(.331,.44,.536,.87),(.494,.64,.725,.87),(.724,.71,.995,.87)]
    elif anim=='kick':
        # The top row faces right; headings name the leg, not the travel direction.
        boxes=[(.02,.18,.195,.50),(.28,.18,.445,.50),(.49,.18,.724,.50),(.80,.18,.98,.50)]
        a=np.array(im).copy();yy,xx=np.indices((h,w));v=a.astype('int16')
        spark=(xx>w*.698)&(xx<w*.77)&(yy<h*.38)&(v[:,:,0]>190)&(v[:,:,1]>90)&(v[:,:,2]<140)
        a[spark]=255;im=Image.fromarray(a)
    elif anim=='elbow':
        boxes=[(.01,.32,.224,.92),(.25,.32,.495,.92),(.495,.32,.733,.92),(.77,.32,.985,.92)]
        # Remove the printed spark; the game's hit effect supplies contact FX.
        a=np.array(im).copy();a[(np.indices((h,w))[1]>w*.708)&(np.indices((h,w))[1]<w*.77) & (np.indices((h,w))[0]<h*.56)]=255
        im=Image.fromarray(a)
    elif anim=='guitar':
        # Five separated cells, with intact contact. Do not import another
        # wrestler's guitar repair or include the surrounding panel rules.
        boxes=[(i/5+.012,.235,(i+1)/5-.012,.87) for i in range(5)]
    else:return None
    result=[]
    for x1,y1,x2,y2 in boxes:
        region=np.zeros((h,w),dtype=bool)
        region[int(y1*h):int(y2*h),int(x1*w):int(x2*w)]=True
        found=clean_mask(im,region,minheight=32)
        if found:result.append(max(found,key=lambda v:v['area']))
    return result
